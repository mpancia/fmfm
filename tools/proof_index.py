#!/usr/bin/env python3
"""List what the repo proves: every public theorem in Proofs/ with its one-line claim and its reason.
  tools/proof_index.py            print the index
  tools/proof_index.py --write    write docs/PROOFS.md
  tools/proof_index.py --check    fail if docs/PROOFS.md is out of date (make lint runs this)"""
import re, sys, textwrap
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PAT = re.compile(r"/--((?:(?!-/).)*)-/\s*theorem\s+(\S+)", re.S)

def collect():
    rows = []
    for path in sorted((ROOT / "Proofs").glob("*.lean")):
        for doc, name in PAT.findall(path.read_text()):
            text = " ".join(doc.split())
            claim, _, why = text.partition("Why it matters:")
            rows.append((path.stem, name, claim.strip(), why.strip()))
    return rows

def wrap(text):
    return textwrap.fill(text, width=120, break_long_words=False, break_on_hyphens=False)

def render(rows):
    out = ["# What is proved", "",
           "Generated by `tools/proof_index.py --write`; `make lint` fails if it is out of date.",
           "Each entry is a public theorem in `Proofs/`, with the reason it is worth having.",
           "Definitions it relies on are in `Firmware/` (the code) and `Spec/` (helpers for stating it).", ""]
    module = None
    for mod, name, claim, why in rows:
        if mod != module:
            out += [f"## {mod}", ""]
            module = mod
        out += [wrap(f"**`{name}`**: {claim}"), ""]
        if why:
            out += [wrap(f"Why it matters: {why}"), ""]
    return "\n".join(out).rstrip() + "\n"

if __name__ == "__main__":
    text = render(collect())
    target = ROOT / "docs" / "PROOFS.md"
    if "--write" in sys.argv:
        target.write_text(text)
    elif "--check" in sys.argv:
        if not target.exists() or target.read_text() != text:
            print("docs/PROOFS.md is out of date: run tools/proof_index.py --write"); sys.exit(1)
    else:
        print(text)
