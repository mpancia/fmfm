#!/usr/bin/env python3
"""Turn the pixel art in ui/alfred.txt into ui/alfred.h (Alfred the butler, the mascot) and web/alfred.svg, the
simulator's icon, in the CATALOGUE look.

Each character of alfred.txt is one pixel: . clear, K outline, S skin, D skin shadow, E eye, W white, G grey,
B suit, L suit light, A accent (the bow tie). Every row must be 24 characters, and there must be 32 rows.

  tools/gen_alfred.py --write     rewrite ui/alfred.h and web/alfred.svg
  tools/gen_alfred.py --check     fail if either is out of date (make lint runs this)
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LEGEND = ".KSDEWGBLA"
NAMES = ["NONE", "OUTLINE", "SKIN", "SHADE", "EYE", "WHITE", "GREY", "SUIT", "SUIT_LIGHT", "ACCENT"]
WIDTH, HEIGHT, HEAD_ROWS = 24, 32, 13


# the colours alfred_colour in dinghy.c gives each pixel class, in the CATALOGUE look
ICON = {"K": "#000", "S": "#eebe96", "D": "#cd9673", "E": "#14141e", "W": "#f0ece2", "G": "#9696a0",
        "B": "#0f0e12", "L": "#3a3542", "A": "#ff8fb1"}


def pixels():
    rows = (ROOT / "ui/alfred.txt").read_text().split()
    if len(rows) != HEIGHT or any(len(r) != WIDTH for r in rows):
        sys.exit(f"ui/alfred.txt must be {HEIGHT} rows of {WIDTH} characters")
    for r in rows:
        bad = set(r) - set(LEGEND)
        if bad:
            sys.exit(f"ui/alfred.txt: unknown pixel {sorted(bad)}")
    return rows


def icon():
    rows = pixels()
    out = [f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {WIDTH} {HEIGHT}" shape-rendering="crispEdges">']
    for colour in dict.fromkeys(ICON.values()):
        cells = [f"M{x} {y}h1v1h-1z" for y, r in enumerate(rows) for x, c in enumerate(r)
                 if c != "." and ICON[c] == colour]
        out.append(f'<path fill="{colour}" d="{"".join(cells)}"/>')
    out.append("</svg>")
    return "\n".join(out) + "\n"


def render():
    rows = pixels()
    out = ["/* SPDX-License-Identifier: GPL-3.0-only */",
           "/* Generated by tools/gen_alfred.py from ui/alfred.txt. Do not edit by hand. */",
           "#pragma once", "#include <stdint.h>", "",
           "enum { " + ", ".join(f"A_{n}" for n in NAMES) + " };",
           f"#define ALFRED_W {WIDTH}u", f"#define ALFRED_H {HEIGHT}u",
           f"#define ALFRED_HEAD_ROWS {HEAD_ROWS}u                 /* rows above the bow tie: they dip when Alfred bows */",
           "static const uint8_t ALFRED[ALFRED_H][ALFRED_W] = {"]
    for r in rows:
        out.append("    {" + ",".join(str(LEGEND.index(c)) for c in r) + "},")
    out.append("};")
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    outputs = {ROOT / "ui/alfred.h": render(), ROOT / "web/alfred.svg": icon()}
    if "--write" in sys.argv:
        for target, text in outputs.items():
            target.write_text(text)
    elif "--check" in sys.argv:
        for target, text in outputs.items():
            if not target.exists() or target.read_text() != text:
                print(f"{target.relative_to(ROOT)} is out of date: run tools/gen_alfred.py --write")
                sys.exit(1)
    else:
        print(render())
