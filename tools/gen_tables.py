#!/usr/bin/env python3
"""Copy five of Braids' tables from the C sources into Firmware/BraidsData.lean.

The Lean accessors (`Pitch.incrementTable`, `Percussion.cutoffTable`, `NoiseSetup.rateTable`,
`VowelsSetup.vowelAmplitudeAt`, `WavetablesSetup.tableSteps`) are externs the C fills from these tables; their
Lean bodies are the copies here, so the proofs about the data (`Proofs/BraidsData.lean`) check the numbers
Braids ships. Each copy is a `match` with one arm per entry and a last arm that repeats the final entry.

  tools/gen_tables.py --write     rewrite Firmware/BraidsData.lean
  tools/gen_tables.py --check     fail if Firmware/BraidsData.lean is out of date (make lint runs this)
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RESOURCES = "voices/braids/resources.cc"
OSCILLATOR = "voices/braids/digital_oscillator.cc"


def brace_list(text, name):
    """The integers of `name[] = { ... };` in `text`."""
    match = re.search(rf"\b{re.escape(name)}\[\] = \{{(.*?)\}};", text, re.S)
    if not match:
        sys.exit(f"{name} not found")
    return [int(v) for v in re.findall(r"-?\d+", match.group(1))]


def vowel_amplitudes(text):
    """The 9 by 3 `formant_amplitude` nibbles of `vowels_data`."""
    match = re.search(r"vowels_data\[9\] = \{(.*?)\n\};", text, re.S)
    if not match:
        sys.exit("vowels_data not found")
    rows = re.findall(r"\{\s*\{[^}]*\}\s*,\s*\{([^}]*)\}\s*\}", match.group(1))
    amplitudes = [[int(v) for v in row.split(",")] for row in rows]
    if len(amplitudes) != 9 or any(len(row) != 3 for row in amplitudes):
        sys.exit("vowels_data must be 9 rows of 3 amplitudes")
    return amplitudes


def wavetable_steps(text):
    """The `num_steps` of each of the 20 `wavetable_definitions`."""
    match = re.search(r"wavetable_definitions\[\] = \{(.*?)\n\};", text, re.S)
    if not match:
        sys.exit("wavetable_definitions not found")
    steps = [int(v) for v in re.findall(r"^\{\s*(\d+)\s*,", match.group(1), re.M)]
    if len(steps) != 20:
        sys.exit("wavetable_definitions must have 20 entries")
    return steps


def one_index(name, source, doc, values):
    out = [f"/-- {doc}",
           f"From `{source}`, {len(values)} entries; past the end it repeats the last entry, which the index",
           "proofs show the code never reads. -/",
           f"noncomputable def BraidsData.{name} : Nat → Nat"]
    out += [f"  | {i} => {v}" for i, v in enumerate(values)]
    out.append(f"  | _ => {values[-1]}")
    return out


def render():
    resources = (ROOT / RESOURCES).read_text()
    oscillator = (ROOT / OSCILLATOR).read_text()
    increments = brace_list(resources, "lut_oscillator_increments")
    cutoffs = brace_list(resources, "lut_svf_cutoff")
    rates = brace_list(resources, "lut_granular_envelope_rate")
    if (len(increments), len(cutoffs), len(rates)) != (97, 257, 257):
        sys.exit("unexpected table lengths in resources.cc")
    amplitudes = vowel_amplitudes(oscillator)
    steps = wavetable_steps(oscillator)
    out = ["set_option compiler.extract_closed false", "",
           "/-!",
           f"Generated by tools/gen_tables.py from `{RESOURCES}` and",
           f"`{OSCILLATOR}` (Braids, Emilie Gillet, MIT). Do not edit by hand: `make lint`",
           "checks that this file matches the C.", "",
           "Copies of the tables the Lean accessors read through C, as plain functions on `Nat`, so the",
           "proofs in `Proofs/BraidsData.lean` can check the data. `noncomputable`: nothing here is compiled",
           "into the firmware; the C reads its own copy.",
           "-/", ""]
    out += one_index("oscillatorIncrement", "lut_oscillator_increments",
                     "The phase step at an index of the top octave.", increments)
    out += [""] + one_index("svfCutoff", "lut_svf_cutoff", "The filter cutoff coefficient at an index.",
                            cutoffs)
    out += [""] + one_index("granularEnvelopeRate", "lut_granular_envelope_rate",
                            "The grain envelope rate at an index.", rates)
    out += ["",
            "/-- The amplitude nibble of a formant (0 to 2) of a vowel (0 to 8). From `vowels_data` in",
            f"`{OSCILLATOR}`; past either range it repeats the last entry, which the index",
            "proofs show the code never reads. -/",
            "noncomputable def BraidsData.vowelAmplitude : Nat → Nat → Nat"]
    out += [f"  | {v}, {f} => {a}" for v, row in enumerate(amplitudes) for f, a in enumerate(row)]
    out.append(f"  | _, _ => {amplitudes[-1][-1]}")
    out += [""] + one_index("wavetableSteps", "wavetable_definitions",
                            "How many steps a wavetable (0 to 19) has.", steps)
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    text = render()
    target = ROOT / "Firmware/BraidsData.lean"
    if "--write" in sys.argv:
        target.write_text(text)
    elif "--check" in sys.argv:
        if not target.exists() or target.read_text() != text:
            print("Firmware/BraidsData.lean is out of date: run tools/gen_tables.py --write")
            sys.exit(1)
    else:
        print(text)
