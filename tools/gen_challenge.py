#!/usr/bin/env python3
"""The Comparator challenge: every public theorem of Proofs/ restated with `sorry` for its proof, so that
`lake comparator` can check that Proofs/ proves exactly these statements with no axiom but the three
standard ones. The statements are copied from Proofs/ verbatim; Comparator compares them after
elaboration, so a changed statement in either place is a mismatch, not a silent pass.
  tools/gen_challenge.py            write Challenge.lean and comparator.json
  tools/gen_challenge.py --check    fail if either is out of date (make lint runs this)"""
import json, re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
HEAD = re.compile(r"^theorem\s+(\S+)", re.M)

def proof_start(body):
    """Where the proof begins: the first `:=` that is not a `let` inside the statement."""
    for m in re.finditer(r":=", body):
        line = body[body.rfind("\n", 0, m.start()) + 1:m.start()]
        if not re.search(r"\blet\b", line):
            return m.start()
    raise SystemExit("no proof found in " + body[:60])

def statements():
    """(module, name, statement) for every public theorem, statement as written up to its `:=`."""
    rows = []
    for path in sorted((ROOT / "Proofs").glob("*.lean")):
        text = path.read_text()
        for m in HEAD.finditer(text):
            body = text[m.end():]
            rows.append((path.stem, m.group(1), body[:proof_start(body)].rstrip()))
    return rows

def render(rows):
    out = ["-- Generated by tools/gen_challenge.py from Proofs/; do not edit. `make lint` fails if it is stale.",
           "-- The Comparator challenge: what the firmware promises, as statements without proofs.",
           "-- `lake comparator` checks that Proofs/ proves each of these, with no axiom but propext,",
           "-- Classical.choice and Quot.sound. This module is the only place `sorry` is allowed.",
           "import Firmware", "import Spec", ""]
    module = None
    for mod, name, stmt in rows:
        if mod != module:
            out += [f"-- Proofs/{mod}.lean"]
            module = mod
        out += [f"theorem {name}{stmt} := sorry", ""]
    return "\n".join(out).rstrip() + "\n"

def config(rows):
    return json.dumps({
        "challenge_module": "Challenge",
        "solution_module": "Proofs",
        "theorem_names": [name for _, name, _ in rows],
        "permitted_axioms": ["propext", "Quot.sound", "Classical.choice"],
    }, indent=2) + "\n"

if __name__ == "__main__":
    rows = statements()
    want = {ROOT / "Challenge.lean": render(rows), ROOT / "comparator.json": config(rows)}
    if "--check" in sys.argv:
        stale = [p.name for p, text in want.items() if not p.exists() or p.read_text() != text]
        if stale:
            print(f"{', '.join(stale)} out of date: run tools/gen_challenge.py"); sys.exit(1)
    else:
        for p, text in want.items():
            p.write_text(text)
        print(f"{len(rows)} theorems in Challenge.lean and comparator.json")
